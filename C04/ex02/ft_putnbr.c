#include <unistd.h>

void	ft_putnbr(int nb)
{
	long long	n;

	n = nb;
	if (n < 0)
	{
		write(1, "-", 1);
		n = -n;
	}
	if (n < 10)
		write(1, &"0123456789"[n], 1);
	else
	{
		ft_putnbr(n / 10);
		ft_putnbr(n % 10);
	}
}
